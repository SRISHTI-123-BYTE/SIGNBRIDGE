def get_sign_language_by_id(lang_id: str) -> Optional[Dict[str, Any]]:
    """Lookup an official Standard Indian Sign Language variety by its ID."""
    lang_id_normalized = lang_id.strip().lower()
    for item in INDIAN_SIGN_LANGUAGES:
        if item["id"].lower() == lang_id_normalized:
            return item
    return None
